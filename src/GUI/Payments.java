    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {
            if (selectedCards.isEmpty()) {
                JOptionPane.showMessageDialog(null, "No student selected.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            if (model.getRowCount() == 0) {
                JOptionPane.showMessageDialog(null, "No items in the invoice.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String paymentMethod = (String) jComboBox1.getSelectedItem();
            if (paymentMethod == null || paymentMethod.equals("Select")) {
                JOptionPane.showMessageDialog(null, "Please select a payment method.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String paymentMethodId = method.get(paymentMethod);
            String studentId = selectedCards.values().iterator().next();

            // Get total paid and calculate balance
            double totalAmount = Double.parseDouble(jFormattedTextField1.getText());
            double amountPaid = Double.parseDouble(jFormattedTextField2.getText());
            double balance = Math.max(totalAmount - amountPaid, 0.0);

            // Step 1: Insert into Payment Table
            String insertPaymentQuery = "INSERT INTO payment (student_studentId, amountPaid, balance, date, payment_method_id) VALUES "
                    + "('" + studentId + "', '" + amountPaid + "', '" + balance + "', CURDATE(), '" + paymentMethodId + "')";
            MySQL.executeIUD(insertPaymentQuery);

            // Get the generated paymentId
            ResultSet rs = MySQL.executeSearch("SELECT LAST_INSERT_ID() AS paymentId");
            int paymentId;
            if (rs.next()) {
                paymentId = rs.getInt("paymentId");
            } else {
                throw new Exception("Failed to retrieve generated payment ID.");
            }

            // Step 2: Insert into Payment_Item Table
            for (int i = 0; i < model.getRowCount(); i++) {
                String month = model.getValueAt(i, 0).toString(); // Assuming Month is at column 0
                String subjectName = model.getValueAt(i, 1).toString(); // Assuming Subject is at column 1
                double price = Double.parseDouble(model.getValueAt(i, 2).toString()); // Assuming Price is at column 2
                double dueAmount = price - (amountPaid > price ? price : amountPaid);
                amountPaid -= price;

                // Get classId for the subject
                String classIdQuery = "SELECT classId FROM class c "
                        + "INNER JOIN subject s ON c.subject_subjectId = s.subjectId "
                        + "WHERE s.name = '" + subjectName + "'";
                ResultSet classRs = MySQL.executeSearch(classIdQuery);

                if (classRs.next()) {
                    int classId = classRs.getInt("classId");

                    // Insert into payment_item
                    String insertItemQuery = "INSERT INTO payment_item (payment_paymentId, class_classId, month, amount, dueAmount) VALUES "
                            + "('" + paymentId + "', '" + classId + "', '" + month + "', '" + price + "', '" + dueAmount + "')";
                    MySQL.executeIUD(insertItemQuery);
                } else {
                    JOptionPane.showMessageDialog(null, "Class not found for subject: " + subjectName, "Error", JOptionPane.ERROR_MESSAGE);
                }
            }

            JOptionPane.showMessageDialog(null, "Payments submitted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            clearTableAndReset();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error during submission: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

