    private void loadEnrollmentCards(String studentSearchTerm) {
        try {
            // Query to fetch enrollment details using the many-to-many relationship
            String query = "SELECT she.student_studentId AS studentId, "
                    + "CONCAT(s.fName, ' ', s.lName) AS studentName, "
                    + "CONCAT(t.fName, ' ', t.lName) AS teacherName, "
                    + "subj.name AS subjectName, c.price, c.classId "
                    + "FROM student_has_enrollment she "
                    + "INNER JOIN enrollment e ON she.enrollment_enrollmentId = e.enrollmentId "
                    + "INNER JOIN student s ON she.student_studentId = s.studentId "
                    + "INNER JOIN class c ON e.class_classId = c.classId "
                    + "INNER JOIN teacher t ON c.teacher_teacherId = t.teacherId "
                    + "INNER JOIN subject subj ON c.subject_subjectId = subj.subjectId "
                    + "WHERE s.fName LIKE '%" + studentSearchTerm + "%' "
                    + "OR s.lName LIKE '%" + studentSearchTerm + "%' "
                    + "OR s.studentId LIKE '%" + studentSearchTerm + "%'";

            ResultSet rs = MySQL.executeSearch(query);

            // Clear existing cards
            jPanel5.removeAll();
            jPanel5.setLayout(null); // Free Design Layout

            // Track selected cards and their associated rows
            //Map<JPanel, Integer> selectedCards = new HashMap<>();
            // Initialize card layout parameters
            int x = 10;
            int y = 20;
            int cardWidth = 320;
            int cardHeight = 150;
            int horizontalSpacing = 30;
            int verticalSpacing = 20;

            while (rs.next()) {
                // Fetch details from the result set
                String studentId = rs.getString("studentId");
                String studentName = rs.getString("studentName");
                String teacherName = rs.getString("teacherName");
                String subjectName = rs.getString("subjectName");
                String price = rs.getString("price");
                String classId = rs.getString("classId");

                // Create a card for each enrollment
                JPanel card = new JPanel();
                card.setBounds(x, y, cardWidth, cardHeight);
                card.setLayout(null);
                card.setBackground(Color.WHITE);
                card.setBorder(BorderFactory.createLineBorder(Color.BLACK));

                // Add labels to the card
                JLabel studentLabel = new JLabel("Student: " + studentName);
                studentLabel.setFont(new Font("Poppins", Font.PLAIN, 14));
                studentLabel.setBounds(20, 20, cardWidth - 20, 20);
                card.add(studentLabel);

                JLabel subjectLabel = new JLabel("Subject: " + subjectName);
                subjectLabel.setFont(new Font("Poppins", Font.PLAIN, 14));
                subjectLabel.setBounds(20, 50, cardWidth - 20, 20);
                card.add(subjectLabel);

                JLabel teacherLabel = new JLabel("Teacher: " + teacherName);
                teacherLabel.setFont(new Font("Poppins", Font.PLAIN, 14));
                teacherLabel.setBounds(20, 80, cardWidth - 20, 20);
                card.add(teacherLabel);

                JLabel priceLabel = new JLabel("Price: " + price);
                priceLabel.setFont(new Font("Poppins", Font.PLAIN, 14));
                priceLabel.setBounds(20, 110, cardWidth - 20, 20);
                card.add(priceLabel);

                card.addMouseListener(new MouseAdapter() {
                    @Override
                    public void mouseClicked(MouseEvent e) {
                        int selectedMonth = jMonthChooser1.getMonth() + 1; // Get the selected month
                        if (selectedMonth == 0) {
                            JOptionPane.showMessageDialog(jPanel5, "Please select a month before adding to the invoice.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                            return;
                        }

                        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
                        String month = String.format("%02d", selectedMonth);
                        double priceValue = Double.parseDouble(price);

                        // Check if the card is already selected
                        if (selectedCards.containsKey(card)) {
                            // Card is already selected, reset its state
                            card.setBackground(Color.WHITE);

                            // Dynamically find and remove the row
                            for (int i = 0; i < model.getRowCount(); i++) {
                                Object monthValue = model.getValueAt(i, 0); // Month column
                                Object subjectValue = model.getValueAt(i, 1); // Subject column

                                // Check for null values before comparison
                                if (monthValue != null && subjectValue != null
                                        && monthValue.equals(month) && subjectValue.equals(subjectName)) {
                                    model.removeRow(i);
                                    break;
                                }
                            }

                            selectedCards.remove(card);
                        } else {
                            // If this is the first card being selected, clear the table
                            if (selectedCards.isEmpty()) {
                                model.setRowCount(0); // Clear the table to ensure no blank rows
                            }

                            // Select the card
                            card.setBackground(Color.ORANGE); // Highlight selected card

                            // Add data to the table only if it's not already present
                            boolean rowExists = false;
                            for (int i = 0; i < model.getRowCount(); i++) {
                                Object monthValue = model.getValueAt(i, 0);
                                Object subjectValue = model.getValueAt(i, 1);

                                if (monthValue != null && subjectValue != null
                                        && monthValue.equals(month) && subjectValue.equals(subjectName)) {
                                    rowExists = true;
                                    break;
                                }
                            }

                            if (!rowExists) {
                                model.addRow(new Object[]{month, subjectName, priceValue});
                                selectedCards.put(card, studentId); // No need to track a specific row index
                            }
                        }

                        // Update the total after adding/removing rows
                        updateInvoiceTotal();
                    }
                });

                // Add the card to jPanel5
                jPanel5.add(card);

                // Update position for the next card
                x += cardWidth + horizontalSpacing;
                if (x + cardWidth > jPanel5.getWidth()) {
                    x = 10;
                    y += cardHeight + verticalSpacing;
                }
            }

            // Refresh the panel
            jPanel5.revalidate();
            jPanel5.repaint();

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading enrollment cards: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void filterCards() {
        String studentSearchTerm = jTextField1.getText().trim().toLowerCase();

        // If the search field is empty, load all cards
        if (studentSearchTerm.isEmpty()) {
            loadEnrollmentCards(""); // Load all cards
        } else {
            loadEnrollmentCards(studentSearchTerm); // Filter cards based on the search query

        }

    }

    private void updateInvoiceTotal() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            double total = 0.0;

            for (int i = 0; i < model.getRowCount(); i++) {
                total += Double.parseDouble(model.getValueAt(i, 2).toString());
            }

            jFormattedTextField1.setText(String.format("%.2f", total));

            double paid = jFormattedTextField2.getText().isEmpty() ? 0.0 : Double.parseDouble(jFormattedTextField2.getText());
            double balance = Math.max(total - paid, 0.0);

            jFormattedTextField3.setText(String.format("%.2f", Math.max(total - paid, 0.0)));
            jFormattedTextField4.setText(String.format("%.2f", balance));
        } catch (NumberFormatException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Invalid data in invoice.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void clearTableAndReset() {
        // Clear all rows from jTable1
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        // Reset any other states, e.g., selected cards
        for (JPanel card : selectedCards.keySet()) {
            card.setBackground(Color.WHITE);
        }
        selectedCards.clear();

        selectedCards.clear();
        jFormattedTextField1.setText("");
        jFormattedTextField2.setText("");
        jFormattedTextField3.setText("");
        jFormattedTextField4.setText("");
        jComboBox1.setSelectedIndex(0);
    }

    private void setupListeners() {
        // Listener for jFormattedTextField2 to update balance dynamically
        jFormattedTextField2.addKeyListener(new KeyAdapter() {
            @Override
            public void keyReleased(KeyEvent e) {
                try {
                    double total = jFormattedTextField1.getText().isEmpty() ? 0.0 : Double.parseDouble(jFormattedTextField1.getText());
                    double paid = jFormattedTextField2.getText().isEmpty() ? 0.0 : Double.parseDouble(jFormattedTextField2.getText());
                    double balance = Math.max(paid - total, 0.0);

                    jFormattedTextField4.setText(String.format("%.2f", balance));
                } catch (NumberFormatException ex) {
                    jFormattedTextField4.setText("");
                }
            }
        });
    }

