    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // sign In
        
        String username = jTextField1.getText().trim();
        String password = String.valueOf(jPasswordField1.getPassword()).trim();

        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your username", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your password", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                String query = "SELECT * FROM `user` WHERE `username` = '" + username + "' AND `password` = '" + password + "'";
                ResultSet resultSet = MySQL.executeSearch(query);

                if (resultSet.next()) {
                    // Login success
                    String fName = resultSet.getString("fName");
                    String lName = resultSet.getString("lName");
                    setLoggedInUsername(username); 

                    JOptionPane.showMessageDialog(this, "Welcome.. " , "Success", JOptionPane.INFORMATION_MESSAGE);

                    // Redirect to the Dashboard GUI
                    new SideBar(username).setVisible(true);
                    this.dispose(); 
                } else {
                    // Login failed
                    JOptionPane.showMessageDialog(this, "Invalid username or password", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "An error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

