    private void loadClasses() {
        try {
            ResultSet rs = MySQL.executeSearch(
                    "SELECT c.classId, t.fName AS teacherName, s.name AS subjectName "
                    + "FROM class c "
                    + "INNER JOIN teacher t ON c.teacher_teacherId = t.teacherId "
                    + "INNER JOIN subject s ON c.subject_subjectId = s.subjectId"
            );

            Vector<String> classes = new Vector<>();
            classes.add("Select Class"); // Default option

            while (rs.next()) {
                String classId = rs.getString("classId");
                String teacherName = rs.getString("teacherName");
                String subjectName = rs.getString("subjectName");

                String displayValue = teacherName + " - " + subjectName;
                classes.add(displayValue);
                classs.put(displayValue, classId); // Map display value to classId
            }

            jComboBox1.setModel(new DefaultComboBoxModel<>(classes));
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading classes: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

