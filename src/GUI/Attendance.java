    private void loadClassAttendanceOrStudents(String classId, java.sql.Date sqlDate) {
        try {
            // Query to check if attendance exists for the selected class and date
            String attendanceQuery = "SELECT s.fName, s.lName, s.nic, a.status_id "
                    + "FROM attendance a "
                    + "INNER JOIN student s ON a.student_studentId = s.studentId "
                    + "WHERE a.class_classId = '" + classId + "' AND a.date = '" + sqlDate + "'";

            ResultSet attendanceResultSet = MySQL.executeSearch(attendanceQuery);

            // Table model for attendance or enrolled students
            javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
                    new Object[][]{},
                    new String[]{"Student Name", "Student NIC", "Presence"}
            ) {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return column == 2; // Only the "Presence" column is editable
                }

                @Override
                public Class<?> getColumnClass(int columnIndex) {
                    return columnIndex == 2 ? Boolean.class : String.class; // Checkbox for "Presence"
                }
            };

            // If attendance records exist, load them
            if (attendanceResultSet.next()) {
                do {
                    String fullName = attendanceResultSet.getString("fName") + " " + attendanceResultSet.getString("lName");
                    String nic = attendanceResultSet.getString("nic");
                    boolean presence = attendanceResultSet.getString("status_id").equals("4"); // Present if status_id = 4
                    model.addRow(new Object[]{fullName, nic, presence});
                } while (attendanceResultSet.next());
            } else {
                // If no attendance exists, load enrolled students
                String enrolledStudentsQuery = "SELECT s.fName, s.lName, s.nic "
                        + "FROM student s "
                        + "INNER JOIN student_has_enrollment she ON s.studentId = she.student_studentId "
                        + "INNER JOIN enrollment e ON she.enrollment_enrollmentId = e.enrollmentId "
                        + "WHERE e.class_classId = '" + classId + "'";

                ResultSet enrolledResultSet = MySQL.executeSearch(enrolledStudentsQuery);
                while (enrolledResultSet.next()) {
                    String fullName = enrolledResultSet.getString("fName") + " " + enrolledResultSet.getString("lName");
                    String nic = enrolledResultSet.getString("nic");
                    model.addRow(new Object[]{fullName, nic, false}); // Default presence is unchecked
                }
            }

            // Set the model to the table
            jTable1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void submitAttendance() {
        try {
            String selectedClass = (String) jComboBox1.getSelectedItem();
            if (selectedClass == null || selectedClass.equals("Select Class")) {
                JOptionPane.showMessageDialog(this, "Please select a class!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String classId = classs.get(selectedClass);
            if (classId == null) {
                JOptionPane.showMessageDialog(this, "Invalid class selected!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            java.util.Date date = jDateChooser1.getDate();
            if (date == null) {
                JOptionPane.showMessageDialog(this, "Please select a date!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            java.sql.Date sqlDate = new java.sql.Date(date.getTime());

            // Loop through the table and insert attendance records
            javax.swing.table.TableModel model = jTable1.getModel();
            for (int i = 0; i < model.getRowCount(); i++) {
                String studentName = (String) model.getValueAt(i, 0); // Student name (not used for DB)
                String studentNIC = (String) model.getValueAt(i, 1); // Student NIC
                boolean presence = (boolean) model.getValueAt(i, 2); // Presence

                // Get studentId using NIC
                ResultSet rs = MySQL.executeSearch(
                        "SELECT studentId FROM student WHERE nic = '" + studentNIC + "'"
                );
                if (rs.next()) {
                    String studentId = rs.getString("studentId");

                    // Check if an attendance record already exists
                    ResultSet attendanceCheck = MySQL.executeSearch(
                            "SELECT * FROM attendance WHERE class_classId = '" + classId + "' "
                            + "AND student_studentId = '" + studentId + "' AND date = '" + sqlDate + "'"
                    );

                    if (attendanceCheck.next()) {
                        // Update existing attendance record
                        String updateQuery = "UPDATE attendance SET status_id = '" + (presence ? "4" : "5") + "' "
                                + "WHERE class_classId = '" + classId + "' AND student_studentId = '" + studentId + "' AND date = '" + sqlDate + "'";
                        MySQL.executeIUD(updateQuery);
                    } else {
                        // Insert new attendance record
                        String insertQuery = "INSERT INTO attendance (class_classId, student_studentId, date, status_id) "
                                + "VALUES ('" + classId + "', '" + studentId + "', '" + sqlDate + "', '" + (presence ? "4" : "5") + "')";
                        MySQL.executeIUD(insertQuery);
                    }
                }
            }

            JOptionPane.showMessageDialog(this, "Attendance submitted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

            // Reset form
            resetForm();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error submitting attendance: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

