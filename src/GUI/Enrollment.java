    private void selectClassCard(JPanel classCard, String classId) {
        if (selectedClassIds.contains(classId)) {
            // Deselect the class
            selectedClassIds.remove(classId);
            classCard.setBackground(Color.WHITE); // Reset the background color
        } else {
            // Select the class
            selectedClassIds.add(classId);
            classCard.setBackground(Color.ORANGE); // Highlight the card
        }
    }

    private void loadStudent() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT studentId, CONCAT(fName, ' ', lName) AS fullName FROM student");

            Vector<String> vector = new Vector<>();
            vector.add("Select");

            while (resultSet.next()) {
                String teacherName = resultSet.getString("fullName");
                String teacherId = resultSet.getString("studentId");
                vector.add(teacherName);
                student.put(teacherName, teacherId); // Map teacher name to ID
            }

            DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>(vector);
            jComboBox1.setModel(model);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading teachers: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

