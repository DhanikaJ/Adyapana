    public static void setDateTime(JLabel dateLabel, JLabel timeLabel) {
        new Thread(() -> {
            while (true) {
                LocalDate currentDate = LocalDate.now();
                DateTimeFormatter dateFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd");
                String formattedDate = currentDate.format(dateFormatter);

                LocalTime currentTime = LocalTime.now();
                DateTimeFormatter timeFormatter = DateTimeFormatter.ofPattern("HH:mm:ss");
                String formattedTime = currentTime.format(timeFormatter);

                // Update the labels on the Swing GUI
                if (dateLabel != null) {
                    dateLabel.setText(formattedDate);
                }
                if (timeLabel != null) {
                    timeLabel.setText(formattedTime);
                }

                try {
                    Thread.sleep(1000);
                } catch (InterruptedException e) {
                    System.err.println("Thread interrupted: " + e.getMessage());
                }
            }
        }).start();
    }

    private void logout() {
        // Show a confirmation dialog
        int response = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to log out?",
                "Logout Confirmation",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (response == javax.swing.JOptionPane.YES_OPTION) {
            // Close the current window
            this.dispose();
            // Optionally, redirect to the login screen
            new SignIn().setVisible(true); // Replace LoginScreen with your actual login class
        }
    }
