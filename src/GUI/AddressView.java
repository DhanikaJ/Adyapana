    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String line1 = jTextField1.getText().trim();
            String line2 = jTextField2.getText().trim();
            String selectedCity = jComboBox1.getSelectedItem().toString();

            if (line1.isEmpty() || selectedCity.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Address Line 1 and City are mandatory!", "Warning", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String cityId = cityMap.get(selectedCity);

            String query = "INSERT INTO address (line1, line2, city_id) VALUES ('" + line1 + "', '" + line2 + "', '" + cityId + "')";
            MySQL.executeIUD(query);

            JOptionPane.showMessageDialog(this, "Address added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            reset();
            loadAddress();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error while adding address: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable3MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable3MouseClicked
        int selectedRow = jTable3.getSelectedRow();

        // Single-click behavior: Load data into AddressView inputs
        if (selectedRow != -1 && evt.getClickCount() == 1) {
            jTextField1.setText(jTable3.getValueAt(selectedRow, 1).toString());
            jTextField2.setText(jTable3.getValueAt(selectedRow, 2).toString());
            jComboBox1.setSelectedItem(jTable3.getValueAt(selectedRow, 3).toString());
        }

        // Double-click behavior: Transfer data to Student GUI
        if (selectedRow != -1 && evt.getClickCount() == 2) {
            String addressId = jTable3.getValueAt(selectedRow, 0).toString();
            String line1 = jTable3.getValueAt(selectedRow, 1).toString();
            String line2 = jTable3.getValueAt(selectedRow, 2).toString();
            String city = jTable3.getValueAt(selectedRow, 3).toString();

            // Assuming `studentInstance` is a reference to the Student GUI
            if (parentStudent != null) {
                parentStudent.setSelectedAddressId(addressId);
            } else if(parentTeacher != null){
                parentTeacher.setSelectedAddressId(addressId);
            }
            this.dispose(); // Close AddressView dialog after transferring data
        }
    }//GEN-LAST:event_jTable3MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        try {
            int selectedRow = jTable3.getSelectedRow();
            if (selectedRow == -1) {
                JOptionPane.showMessageDialog(this, "Please select an address to update!", "Warning", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String addressId = jTable3.getValueAt(selectedRow, 0).toString();
            String line1 = jTextField1.getText().trim();
            String line2 = jTextField2.getText().trim();
            String selectedCity = jComboBox1.getSelectedItem().toString();

            if (line1.isEmpty() || selectedCity.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Address Line 1 and City are mandatory!", "Warning", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String cityId = cityMap.get(selectedCity);

            String query = "UPDATE address SET line1 = '" + line1 + "', line2 = '" + line2 + "', city_id = '" + cityId + "' WHERE id = '" + addressId + "'";
            MySQL.executeIUD(query);

            JOptionPane.showMessageDialog(this, "Address updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            reset();
            loadAddress();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error while updating address: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            int selectedRow = jTable3.getSelectedRow();
            if (selectedRow == -1) {
                JOptionPane.showMessageDialog(this, "Please select an address to remove!", "Warning", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String addressId = jTable3.getValueAt(selectedRow, 0).toString();

            int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this address?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                String query = "DELETE FROM address WHERE id = '" + addressId + "'";
                MySQL.executeIUD(query);

                JOptionPane.showMessageDialog(this, "Address removed successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                reset();
                loadAddress();
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error while removing address: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton3ActionPerformed


