    private void loadSubjects() {
        try {
            String query = "SELECT * FROM subject";
            ResultSet rs = MySQL.executeSearch(query);

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing rows
            subjectIdList.clear();

            while (rs.next()) {
                Vector<String> row = new Vector<>();
                row.add(rs.getString("name"));
                row.add(rs.getString("credits"));
                row.add(rs.getString("description"));
                model.addRow(row);
                subjectIdList.add(rs.getString("subjectId"));
            }

            jTable1.setModel(model);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading subjects: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadSubjectcombo() {

        try {

            ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `subject`");

            Vector<String> vector = new Vector<>();
            vector.add("Select");

            while (resultSet.next()) {
                vector.add(resultSet.getString("name"));
                subjectMap.put(resultSet.getString("name"), resultSet.getString("subjectId"));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void loadTeachers() {
        try {
            ResultSet resultSet = MySQL.executeSearch("SELECT teacherId, CONCAT(fName, ' ', lName) AS fullName FROM teacher");

            Vector<String> vector = new Vector<>();
            vector.add("Select");

            while (resultSet.next()) {
                String teacherName = resultSet.getString("fullName");
                String teacherId = resultSet.getString("teacherId");
                vector.add(teacherName);
                teacherMap.put(teacherName, teacherId); // Map teacher name to ID
            }

            DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>(vector);
            jComboBox2.setModel(model);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading teachers: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

