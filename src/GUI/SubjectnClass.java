    private void searchSubjects() {
        try {
            String searchQuery = jTextField1.getText().trim().toLowerCase();
            String query = "SELECT * FROM subject WHERE LOWER(name) LIKE '%" + searchQuery
                    + "%' OR LOWER(description) LIKE '%" + searchQuery + "%'";
            ResultSet rs = MySQL.executeSearch(query);

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing rows

            while (rs.next()) {
                Vector<String> row = new Vector<>();
                row.add(rs.getString("name"));
                row.add(rs.getString("credits"));
                row.add(rs.getString("description"));
                model.addRow(row);
            }

            jTable1.setModel(model);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error searching subjects: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void addTimeSlot() {
        try {
            // Get start and end times from the formatted text fields
            String startTime = jFormattedTextField1.getText().trim();
            String endTime = jFormattedTextField2.getText().trim();

            // Validate inputs
            if (startTime.isEmpty() || endTime.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Start time and end time cannot be empty!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            if (startTime.equals(endTime)) {
                JOptionPane.showMessageDialog(this, "Start time and end time cannot be the same!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Check if the time slot already exists in the database
            String checkQuery = "SELECT * FROM time_slot WHERE stime = '" + startTime + "' AND etime = '" + endTime + "'";
            ResultSet rs = MySQL.executeSearch(checkQuery);

            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "Time slot already exists!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Insert the new time slot into the database
            String insertQuery = "INSERT INTO time_slot (stime, etime) VALUES ('" + startTime + "', '" + endTime + "')";
            MySQL.executeIUD(insertQuery);

            // Add the new time slot button to jPanel7
            addTimeSlotButton(startTime, endTime);

            // Notify the user
            JOptionPane.showMessageDialog(this, "Time slot added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error adding time slot: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void addTimeSlotButton(String startTime, String endTime) {
        try {
            // Ensure jPanel7 has GridBagLayout
            if (!(jPanel7.getLayout() instanceof GridBagLayout)) {
                jPanel7.setLayout(new GridBagLayout());
            }

            // Create a new button for the time slot
            String timeSlot = startTime + " - " + endTime;
            JButton timeButton = new JButton(timeSlot);
            timeButton.setPreferredSize(new Dimension(200, 50)); // Set button size
            timeButton.setFont(new Font("Poppins", Font.BOLD, 14));
            timeButton.setBackground(new Color(41, 128, 185)); // Blue background
            timeButton.setForeground(Color.WHITE);

            // Add ActionListener for the button
            timeSlotButtonGroup.add(timeButton);

            timeButton.addActionListener(e -> {
                jTextField7.setText(timeSlot); // Set the time slot string in jTextField7
            });

            // Add button to jPanel7 with GridBagLayout
            GridBagConstraints gbc = new GridBagConstraints();
            gbc.insets = new Insets(5, 5, 5, 5); // Add spacing between buttons
            gbc.gridx = jPanel7.getComponentCount() % 4; // Max 4 buttons per row
            gbc.gridy = jPanel7.getComponentCount() / 4;

            jPanel7.add(timeButton, gbc);
            jPanel7.revalidate();
            jPanel7.repaint();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error adding button: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadExistingTimeButtons() {
        try {
            // Ensure jPanel7 has GridBagLayout
            if (!(jPanel7.getLayout() instanceof GridBagLayout)) {
                jPanel7.setLayout(new GridBagLayout());
            }

            // Clear existing buttons in jPanel7
            jPanel7.removeAll();

            // Query to fetch existing time slots
            String query = "SELECT stime, etime FROM time_slot";
            ResultSet rs = MySQL.executeSearch(query);

            // GridBagConstraints for placing components
            GridBagConstraints gbc = new GridBagConstraints();
            gbc.insets = new Insets(5, 5, 5, 5); // Padding between buttons
            gbc.gridx = 0;
            gbc.gridy = 0;

            // Dynamically create buttons for each time slot
            while (rs.next()) {
                String startTime = rs.getString("stime");
                String endTime = rs.getString("etime");
                String timeSlot = startTime + " - " + endTime;

                // Create a new button for the time slot
                JButton timeButton = new JButton(timeSlot);
                timeButton.setPreferredSize(new Dimension(200, 50)); // Button size
                timeButton.setFont(new Font("Poppins", Font.BOLD, 14));
                timeButton.setBackground(new Color(41, 128, 185)); // Blue background
                timeButton.setForeground(Color.WHITE);

                timeButton.addActionListener(e -> {
                    jTextField7.setText(timeSlot); // Set the time slot string in jTextField7
                });

                // Set grid position for the button
                gbc.gridx = jPanel7.getComponentCount() % 4; // Max 4 buttons per row
                gbc.gridy = jPanel7.getComponentCount() / 4;

                // Add button to jPanel7
                jPanel7.add(timeButton, gbc);
            }

            // Refresh jPanel7
            jPanel7.revalidate();
            jPanel7.repaint();

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading time slots: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void createClass() {
        try {
            // Fetch selected values
            String selectedSubject = (String) jComboBox1.getSelectedItem();
            String selectedTeacher = (String) jComboBox2.getSelectedItem();
            String room = jTextField6.getText().trim();
            String price = jFormattedTextField3.getText().trim();
            String selectedTimeSlot = jTextField7.getText().trim(); // Get time slot from jTextField7

            // Validate inputs
            if (selectedSubject == null || selectedSubject.equals("Select")
                    || selectedTeacher == null || selectedTeacher.equals("Select")
                    || room.isEmpty() || price.isEmpty() || selectedTimeSlot.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all required fields and select a time slot!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Get the subjectId from subjectMap
            String subjectId = subjectMap.get(selectedSubject);
            if (subjectId == null) {
                JOptionPane.showMessageDialog(this, "Invalid subject selection!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Validate price as numeric
            if (!price.matches("\\d+(\\.\\d+)?")) {
                JOptionPane.showMessageDialog(this, "Price must be a numeric value!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Parse teacherId from teacherMap (if using a similar mapping for teachers)
            String teacherId = teacherMap.get(selectedTeacher);
            if (teacherId == null) {
                JOptionPane.showMessageDialog(this, "Invalid teacher selection!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Get time slot ID from the database
            String[] times = selectedTimeSlot.split(" - ");
            String startTime = times[0];
            String endTime = times[1];
            String timeSlotIdQuery = "SELECT id FROM time_slot WHERE stime = '" + startTime + "' AND etime = '" + endTime + "'";
            ResultSet rs = MySQL.executeSearch(timeSlotIdQuery);

            if (!rs.next()) {
                JOptionPane.showMessageDialog(this, "Selected time slot is invalid!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            int timeSlotId = rs.getInt("id");

            // Insert the class into the database
            String insertQuery = "INSERT INTO class (subject_subjectId, teacher_teacherId, room, price, time_slot_id, status_id) "
                    + "VALUES ('" + subjectId + "', '" + teacherId + "', '" + room + "', '" + price + "', '" + timeSlotId + "',1)";
            MySQL.executeIUD(insertQuery);

            JOptionPane.showMessageDialog(this, "Class created successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            clearClassFields();
            //Enrollment.load
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error creating class: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }


    

